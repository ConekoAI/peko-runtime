//! Channel wire types — Phase 11a extension of `peko-protocol`.
//!
//! ADR-047 (slot number; assign at PR-1 merge). The full multi-principal
//! chat primitive lives in `peko-channel` (separate crate, peer of
//! `peko-cron` / `peko-quota` / `peko-protocol`); the *wire* types live
//! here so CLI / daemon / share-me can all agree on a shape without each
//! carrying its own private variant.
//!
//! ## Deps rule
//!
//! `peko-protocol` depends only on `serde` + `serde_json` (per
//! `Cargo.toml:10-12` and the lib doc on lines 5-18 of `lib.rs`). Principal
//! DIDs in this module are `String` (parsed to `peko_subject::PrincipalId`
//! at the consumer boundary). Timestamps are RFC3339 strings (the project
//! convention — see `peko_cron::ScheduleKind::At { at: String }`).
//!
//! ## Convention mirrors
//!
//! - `ChannelId` is a `String`-newtype, mirroring `peko_subject::PrincipalId`
//!   at `peko-rs/subject/src/lib.rs:25-27`.
//! - `ChannelEvent` is a tagged enum with `tag = "kind"` and
//!   `rename_all = "snake_case"`, mirroring `peko_cron::ScheduleKind` at
//!   `peko-rs/cron/src/tools/mod.rs:54-56`.
//! - Round-trip tests at the bottom pin exact JSON literals, mirroring
//!   `peko-rs/protocol/src/ipc.rs:81-107`.

use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// ChannelId
// ---------------------------------------------------------------------------

/// Channel identifier. Opaque `String` newtype.
///
/// Wire shape: bare string `"chan_<8 base36>"`. Generated by
/// [`ChannelId::generate`]; validated by [`ChannelId::parse`] which
/// enforces the prefix. The inner field serializes directly to a JSON
/// string (no `#[serde(transparent)]` — the project doesn't use it,
///
/// matching `peko_subject::PrincipalId`).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct ChannelId(pub String);

impl ChannelId {
    /// Prefix for all generated channel ids. Mirrors `peko_plan::NodeId::PREFIX`.
    pub const PREFIX: &'static str = "chan_";

    /// Length of the random suffix. Eight base36 chars gives 36^8 ≈ 2.8T
    /// possibilities — the same entropy budget used by `peko_plan::NodeId`
    /// (`schema.rs:49`) and `peko_plan::PlanRecord::plan_id` (`schema.rs:143`).
    const SUFFIX_LEN: usize = 8;

    /// Generate a fresh, unique id. Uses the same splitmix64-style
    /// entropy mixing as `peko_plan::schema::rand_u32` (`schema.rs:485-504`).
    pub fn generate() -> Self {
        Self(format!("{}{}", Self::PREFIX, generate_base36_suffix()))
    }

    /// Parse a string back into a `ChannelId`, validating the prefix and
    /// the 8 base36 suffix. Returns `None` (rather than erroring) so
    /// callers in deserialize paths can decide to skip unknown ids.
    pub fn parse(s: &str) -> Option<Self> {
        let rest = s.strip_prefix(Self::PREFIX)?;
        if rest.len() != Self::SUFFIX_LEN {
            return None;
        }
        if !rest.bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()) {
            // accept 0-9a-z only (matches peko-plan's BASE36)
            let valid = rest
                .bytes()
                .all(|b| b.is_ascii_digit() || b.is_ascii_lowercase());
            if !valid {
                return None;
            }
        }
        Some(Self(s.to_string()))
    }

    /// Borrow the inner string.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for ChannelId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

// ---------------------------------------------------------------------------
// ChannelEvent
// ---------------------------------------------------------------------------

/// Causal-ordered event log for one channel.
///
/// Wire shape (one example per variant):
///
/// ```json
/// {"kind":"created","channel":"chan_a1b2c3d4","creator":"prin_xyz","name":"design-sync","at":"2026-08-05T12:00:00Z"}
/// {"kind":"posted","channel":"chan_a1b2c3d4","author":"prin_xyz","parent":null,"text":"hi","at":"2026-08-05T12:01:00Z"}
/// {"kind":"posted","channel":"chan_a1b2c3d4","author":"prin_qrs","parent":"node_xyz12345","text":"reply","at":"2026-08-05T12:02:00Z"}
/// {"kind":"member_joined","channel":"chan_a1b2c3d4","member":"prin_qrs","at":"2026-08-05T12:00:30Z"}
/// {"kind":"member_left","channel":"chan_a1b2c3d4","member":"prin_qrs","at":"2026-08-05T12:30:00Z"}
/// ```
///
/// `parent` carries a `peko_plan::NodeId` opaque-string reference to the
/// message being replied to; `null` for root posts (the adapter enforces
/// at-most-one parent — see `peko_channel::plan_channel`).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ChannelEvent {
    /// Channel creation. Fires once at the top of the event log.
    Created {
        channel: ChannelId,
        creator: String,
        name: String,
        at: String,
    },
    /// A message authored by `author`. `parent` references the prior
    /// message being replied to; `None` for the channel's first post.
    Posted {
        channel: ChannelId,
        author: String,
        parent: Option<String>,
        text: String,
        at: String,
    },
    /// A principal was invited / joined the channel. Append-only — a
    /// subsequent `MemberLeft` carries the inverse.
    MemberJoined {
        channel: ChannelId,
        member: String,
        at: String,
    },
    /// A principal left (or was removed from) the channel.
    MemberLeft {
        channel: ChannelId,
        member: String,
        at: String,
    },
}

impl ChannelEvent {
    /// Wire-tag discriminant. Mirrors `CronJobAction::kind_label` at
    /// `peko-rs/cron/src/tools/mod.rs:158-165`.
    pub fn kind(&self) -> &'static str {
        match self {
            Self::Created { .. } => "created",
            Self::Posted { .. } => "posted",
            Self::MemberJoined { .. } => "member_joined",
            Self::MemberLeft { .. } => "member_left",
        }
    }
}

