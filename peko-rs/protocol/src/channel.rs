/// Causal-ordered event log for one channel.
///
/// Wire shape (one example per variant):
///
/// ```json
/// {"kind":"created","channel":"chan_a1b2c3d4","creator":"prin_xyz","name":"design-sync","at":"2026-08-05T12:00:00Z"}
/// {"kind":"posted","channel":"chan_a1b2c3d4","author":"prin_xyz","parent":null,"text":"hi","at":"2026-08-05T12:01:00Z"}
/// {"kind":"posted","channel":"chan_a1b2c3d4","author":"prin_qrs","parent":"node_xyz12345","text":"reply","at":"2026-08-05T12:02:00Z"}
/// {"kind":"member_joined","channel":"chan_a1b2c3d4","member":"prin_qrs","at":"2026-08-05T12:00:30Z"}
/// {"kind":"member_left","channel":"chan_a1b2c3d4","member":"prin_qrs","at":"2026-08-05T12:30:00Z"}
/// ```
///
/// `parent` carries a `peko_plan::NodeId` opaque-string reference to the
/// message being replied to; `null` for root posts (the adapter enforces
/// at-most-one parent — see `peko_channel::plan_channel`).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ChannelEvent {
    /// Channel creation. Fires once at the top of the event log.
    Created {
        channel: ChannelId,
        creator: String,
        name: String,
        at: String,
    },
    /// A message authored by `author`. `parent` references the prior
    /// message being replied to; `None` for the channel's first post.
    Posted {
        channel: ChannelId,
        author: String,
        parent: Option<String>,
        text: String,
        at: String,
    },
    /// A principal was invited / joined the channel. Append-only — a
    /// subsequent `MemberLeft` carries the inverse.
    MemberJoined {
        channel: ChannelId,
        member: String,
        at: String,
    },
    /// A principal left (or was removed from) the channel.
    MemberLeft {
        channel: ChannelId,
        member: String,
        at: String,
    },
}

impl ChannelEvent {
    /// Wire-tag discriminant. Mirrors `CronJobAction::kind_label` at
    /// `peko-rs/cron/src/tools/mod.rs:158-165`.
    pub fn kind(&self) -> &'static str {
        match self {
            Self::Created { .. } => "created",
            Self::Posted { .. } => "posted",
            Self::MemberJoined { .. } => "member_joined",
            Self::MemberLeft { .. } => "member_left",
        }
    }
}

