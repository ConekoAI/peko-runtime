//! Channel wire types — Phase 11a extension of `peko-protocol`.
//!
//! ADR-047 (slot number; assign at PR-1 merge). The full multi-principal
//! chat primitive lives in `peko-channel` (separate crate, peer of
//! `peko-cron` / `peko-quota` / `peko-protocol`); the *wire* types live
//! here so CLI / daemon / share-me can all agree on a shape without each
//! carrying its own private variant.
//!
//! ## Deps rule
//!
//! `peko-protocol` depends only on `serde` + `serde_json` (per
//! `Cargo.toml:10-12` and the lib doc on lines 5-18 of `lib.rs`). Principal
//! DIDs in this module are `String` (parsed to `peko_subject::PrincipalId`
//! at the consumer boundary). Timestamps are RFC3339 strings (the project
//! convention — see `peko_cron::ScheduleKind::At { at: String }`).
//!
//! ## Convention mirrors
//!
//! - `ChannelId` is a `String`-newtype, mirroring `peko_subject::PrincipalId`
//!   at `peko-rs/subject/src/lib.rs:25-27`.
//! - `ChannelEvent` is a tagged enum with `tag = "kind"` and
//!   `rename_all = "snake_case"`, mirroring `peko_cron::ScheduleKind` at
//!   `peko-rs/cron/src/tools/mod.rs:54-56`.
//! - Round-trip tests at the bottom pin exact JSON literals, mirroring
//!   `peko-rs/protocol/src/ipc.rs:81-107`.

