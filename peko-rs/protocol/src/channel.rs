/// Channel identifier. Opaque `String` newtype.
///
/// Wire shapes (any of four forms — see [`ChannelKind`]):
///
/// | Wire form             | Kind       | Semantics                                          |
/// |-----------------------|------------|----------------------------------------------------|
/// | `chan_<8 base36>`     | `Bare`     | Plain fire-and-forget post                         |
/// | `principal:<did>`     | `Principal`| RPC: auto-provision DM, await reply up to 1 min   |
/// | `user:<id>`           | `User`     | Fire-and-forget note to a user                    |
/// | `group:<slug>`        | `Group`    | Fire-and-forget post to a group                   |
///
/// Bare ids are generated by [`ChannelId::generate`]; typed ids are
/// minted via [`ChannelId::for_principal`] / [`ChannelId::for_user`] /
/// [`ChannelId::for_group`]. [`ChannelId::parse`] accepts any of the
/// four forms. The inner field serializes directly to a JSON string
/// (no `#[serde(transparent)]` — the project doesn't use it, matching
/// `peko_subject::PrincipalId`).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct ChannelId(pub String);

/// Dispatch kind for a [`ChannelId`]. The runtime branches on this to
/// select the right tool semantics (RPC vs fire-and-forget). Derived
/// from the channel-id prefix; see [`ChannelId::kind`].
///
/// `Serialize` / `Deserialize` are deliberately omitted — this is a
/// runtime-only dispatch enum, not a wire type. The wire form is the
/// `ChannelId` itself.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ChannelKind {
    /// `chan_<8 base36>` — plain fire-and-forget post.
    Bare,
    /// `principal:<did>` — RPC: auto-provision DM channel, await reply.
    Principal,
    /// `user:<id>` — fire-and-forget note to a user (originating-user
    /// gate enforced at the messenger port, not here).
    User,
    /// `group:<slug>` — fire-and-forget post to a group.
    Group,
}

impl ChannelKind {
    /// Wire prefix for this kind. Mirrors the prefix consumed by
    /// [`ChannelId::parse`].
    pub const fn prefix(self) -> &'static str {
        match self {
            Self::Bare => "chan_",
            Self::Principal => "principal:",
            Self::User => "user:",
            Self::Group => "group:",
        }
    }
}

impl ChannelId {
    /// Prefix for randomly-generated bare channel ids. Mirrors
    /// `peko_plan::NodeId::PREFIX`.
    pub const PREFIX: &'static str = "chan_";

    /// Length of the random suffix. Eight base36 chars gives 36^8 ≈ 2.8T
    /// possibilities — the same entropy budget used by `peko_plan::NodeId`
    /// (`schema.rs:49`) and `peko_plan::PlanRecord::plan_id` (`schema.rs:143`).
    const SUFFIX_LEN: usize = 8;

    /// Generate a fresh, unique bare id. Uses the same splitmix64-style
    /// entropy mixing as `peko_plan::schema::rand_u32` (`schema.rs:485-504`).
    pub fn generate() -> Self {
        Self(format!("{}{}", Self::PREFIX, generate_base36_suffix()))
    }

    /// Build a principal-DM channel id from a DID. Wire form:
    /// `principal:<did>`. No BLAKE3 needed — the DID itself is already
    /// cross-runtime-stable, so both sides of a `send_peer` exchange
    /// independently derive the same channel id from the same DID.
    pub fn for_principal(did: &str) -> Self {
        debug_assert!(!did.is_empty(), "for_principal: DID must not be empty");
        Self(format!("principal:{did}"))
    }

    /// Build a user-channel id from a free-form user id. Wire form:
    /// `user:<id>`. The originating-user gate (only the user who
    /// started the current run may be addressed) lives at the
    /// messenger-port layer, not in the id.
    pub fn for_user(id: &str) -> Self {
        debug_assert!(!id.is_empty(), "for_user: id must not be empty");
        Self(format!("user:{id}"))
    }

    /// Build a group-channel id from a free-form slug. Wire form:
    /// `group:<slug>`. The LLM picks the slug (matches today's
    /// `chan_<random>` semantics where the LLM picks the bare
    /// identifier). Prelaunch; cross-principal collisions on the
    /// shared tier are accepted.
    pub fn for_group(slug: &str) -> Self {
        debug_assert!(!slug.is_empty(), "for_group: slug must not be empty");
        Self(format!("group:{slug}"))
    }

    /// Dispatch kind. Pure-string prefix dispatch on the inner
    /// `String`; no allocation.
    pub fn kind(&self) -> ChannelKind {
        if self.0.starts_with("principal:") {
            ChannelKind::Principal
        } else if self.0.starts_with("user:") {
            ChannelKind::User
        } else if self.0.starts_with("group:") {
            ChannelKind::Group
        } else {
            // The default kind is `Bare` for `chan_<...>` ids AND for any
            // unrecognized prefix — `parse` rejects unknown prefixes at
            // the boundary, so a `ChannelId` constructed via the public
            // API always matches one of these four cases at runtime.
            ChannelKind::Bare
        }
    }

    /// Parse a string back into a `ChannelId`, validating the prefix
    /// and (for the bare form) the 8 base36 suffix. Accepts any of the
    /// four wire forms; rejects unknown prefixes and empty
    /// post-prefix content. Returns `None` (rather than erroring) so
    /// callers in deserialize paths can decide to skip unknown ids.
    pub fn parse(s: &str) -> Option<Self> {
        if let Some(rest) = s.strip_prefix(Self::PREFIX) {
            return Self::parse_chan(rest);
        }
        if let Some(rest) = s.strip_prefix(ChannelKind::Principal.prefix()) {
            return Self::parse_typed(ChannelKind::Principal.prefix(), rest);
        }
        if let Some(rest) = s.strip_prefix(ChannelKind::User.prefix()) {
            return Self::parse_typed(ChannelKind::User.prefix(), rest);
        }
        if let Some(rest) = s.strip_prefix(ChannelKind::Group.prefix()) {
            return Self::parse_typed(ChannelKind::Group.prefix(), rest);
        }
        None
    }

    /// Validate the bare-form suffix. Preserved byte-for-byte from the
    /// pre-typed-prefix implementation; the dead-code structure
    /// (`is_ascii_hexdigit && !is_ascii_uppercase`) was an awkward
    /// way to say "0-9a-z" that shipped prelaunch and is pinned by
    /// `channel_id_parse_rejects_invalid`. Out of scope for this PR.
    fn parse_chan(rest: &str) -> Option<Self> {
        if rest.len() != Self::SUFFIX_LEN {
            return None;
        }
        if !rest.bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()) {
            // accept 0-9a-z only (matches peko-plan's BASE36)
            let valid = rest
                .bytes()
                .all(|b| b.is_ascii_digit() || b.is_ascii_lowercase());
            if !valid {
                return None;
            }
        }
        Some(Self(format!("{}{}", Self::PREFIX, rest)))
    }

    /// Validate a typed-prefix form: post-prefix content must be
    /// non-empty. No further format check (the DID / user-id / slug
    /// grammar is enforced at the consumer boundary — `ChannelId`
    /// remains an opaque string).
    fn parse_typed(prefix: &str, rest: &str) -> Option<Self> {
        if rest.is_empty() {
            return None;
        }
        Some(Self(format!("{prefix}{rest}")))
    }

    /// Borrow the inner string.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for ChannelId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

