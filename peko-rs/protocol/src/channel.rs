/// Snapshot of channel membership for IPC responses. The authoritative
/// source of "who is currently a member" is the event log
/// (`MemberJoined` minus `MemberLeft`); this struct is the precomputed
/// answer for callers that don't want to walk the log.
///
/// Mirrors `peko_cron::CronJob`'s flat-struct convention
/// (`peko-rs/cron/src/tools/mod.rs:181-219`): snake_case fields, no
/// `tag`, `Option` fields use `default` + `skip_serializing_if = "is_none"`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct ChannelMembership {
    pub channel: ChannelId,
    pub name: String,
    pub creator: String,
    pub members: Vec<String>,
    /// P1.2 attribution: per-member runtime provenance (local vs
    /// remote). Empty for channels with no remote members; legacy
    /// pre-PR-3b implementations may omit the field entirely
    /// (`#[serde(default)]`).
    #[serde(default)]
    pub member_provenance: Vec<MemberProvenance>,
    /// RFC3339 timestamp of the channel's `Created` event.
    pub created_at: String,
    /// RFC3339 timestamp of the most recent `Member*` event affecting
    /// the membership set.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_membership_change: Option<String>,
}

/// P1.2 attribution: pairs a principal DID with its hosting runtime
/// id. `runtime_id: None` means the principal is local to the
/// receiving runtime; `Some(runtime_id)` means the principal is hosted
/// on a peer runtime that joined the channel via the cross-runtime
/// invite envelope.
///
/// The flat `ChannelMembership::members` list is the back-compat
/// surface; `MemberProvenance` is the richer shape that lets the UI
/// render local vs remote members distinctly. Pre-PR-3b consumers
/// that don't read `member_provenance` see no change to the wire
/// shape — the field uses `#[serde(default)]` and skips when empty.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct MemberProvenance {
    pub principal: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub runtime_id: Option<String>,
}

// ---------------------------------------------------------------------------
// InitialMember — peko-channel cross-runtime PR-3a commit 1
// ---------------------------------------------------------------------------

/// One row of the `initialMembers` list on
/// [`crate::tunnel::TunnelChannelInvite`] (the source runtime's
/// fan-out of a channel invite to a remote runtime's hosting
/// runtime). Pairs a principal DID with the runtime that hosts it.
///
/// Wire shape:
///
/// ```json
/// {"principalDid":"prin_alice"}
/// {"principalDid":"prin_bob","runtimeId":"did:key:zRuntimeB"}
/// ```
///
/// `runtime_id: None` means the principal is local to the source
/// runtime — the receiver should land the row in
/// `members.json`'s local array. `runtime_id: Some(id)` means the
/// principal lives on a peer runtime and the receiver should
/// record a `RemoteMember` row.
///
/// `#[serde(skip_serializing_if = "Option::is_none")]` on
/// `runtime_id` keeps the wire form minimal for the common
/// (single-runtime) case: a 4-line bootstrap envelope shrinks by
/// ~22 bytes per local member. Verified by
/// [`initial_member_skips_none_runtime_id`].
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct InitialMember {
    pub principal_did: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub runtime_id: Option<String>,
}

// ---------------------------------------------------------------------------
// Internal: 8-char lowercase base36 id suffix
// ---------------------------------------------------------------------------

const BASE36: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyz";

/// Same splitmix64-style mixing as `peko_plan::schema::rand_u32`
/// (`schema.rs:485-504`). Wall-clock nanos + monotonic counter + pid —
/// enough for `chan_<8 base36>` ids within a single process lifetime.
fn generate_base36_suffix() -> String {
    use std::sync::atomic::{AtomicU64, Ordering};
    static CTR: AtomicU64 = AtomicU64::new(0);

    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0);
    let pid = std::process::id() as u64;
    let ctr = CTR.fetch_add(1, Ordering::Relaxed);

    let mut z = now
        .wrapping_add(ctr.wrapping_mul(0x9E3779B97F4A7C15))
        .wrapping_add(pid.wrapping_mul(0xBF58476D1CE4E5B9));
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
    z ^= z >> 31;
    let v = (z as u32) ^ ((z >> 32) as u32);

    let mut out = [b'0'; ChannelId::SUFFIX_LEN];
    let mut cur = v;
    for slot in out.iter_mut().rev() {
        *slot = BASE36[(cur % 36) as usize];
        cur /= 36;
    }
    String::from_utf8(out.to_vec()).expect("BASE36 is valid ASCII")
}

