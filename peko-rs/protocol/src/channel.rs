    #[test]
    fn channel_id_parse_round_trip() {
        let id = ChannelId::generate();
        let parsed = ChannelId::parse(id.as_str()).expect("parse generated id");
        assert_eq!(parsed, id);
    }

    #[test]
    fn channel_id_parse_rejects_invalid() {
        // Wrong prefix
        assert!(ChannelId::parse("node_abcdefgh").is_none());
        assert!(ChannelId::parse("chan_").is_none());
        // Wrong suffix length (too short)
        assert!(ChannelId::parse("chan_abc").is_none());
        // Wrong suffix length (too long)
        assert!(ChannelId::parse("chan_abcdefghi").is_none());
        // Uppercase rejected
        assert!(ChannelId::parse("chan_ABCDEFGH").is_none());
        // Non-base36 char
        assert!(ChannelId::parse("chan_abc!defg").is_none());
    }

