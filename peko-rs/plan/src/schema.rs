/// Typed identifier for a single node inside a plan.
///
/// `node_<8 base36 chars>` (DATA_MODEL.md §1.4). Inner is `pub(crate)` —
/// callers reach it via [`NodeId::as_str`].
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct NodeId(String);

impl NodeId {
    pub const PREFIX: &'static str = "node_";

    /// Generate a fresh, unique id. Uses [`rand_u32`] for the suffix;
    /// collisions are astronomically unlikely (36^8 / process = 0 in
    /// any realistic plan size).
    pub fn generate() -> Self {
        Self(format!("{}{}", Self::PREFIX, base36_id(rand_u32())))
    }

    /// Parse a string back into a `NodeId`, validating the prefix and
    /// the 8 base36 suffix.
    pub fn parse(s: &str) -> Result<Self> {
        parse_id_suffix(s, Self::PREFIX)?;
        Ok(Self(s.to_string()))
    }

    /// Borrow the inner string.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for NodeId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl Serialize for NodeId {
    fn serialize<S: serde::Serializer>(&self, ser: S) -> std::result::Result<S::Ok, S::Error> {
        ser.serialize_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for NodeId {
    fn deserialize<D: serde::Deserializer<'de>>(de: D) -> std::result::Result<Self, D::Error> {
        let s = String::deserialize(de)?;
        Self::parse(&s).map_err(serde::de::Error::custom)
    }
}

// ---------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------

/// Cheap, per-process monotonic counter mixed with wall-clock nanos +
/// pid. Avoids pulling in `rand`; the entropy is more than enough for
/// `node_<8 base36>` ids and `plan_<8 base36>` ids within a single
/// process.
///
/// Two consecutive calls within the same nanosecond are distinguished
/// by the counter, so collisions within one process are not possible
/// (would require the counter to wrap, which never happens in u64).
/// The mixing is *not* a CSPRNG; for cryptographic ids callers should
/// supply their own entropy.
fn rand_u32() -> u32 {
    use std::sync::atomic::{AtomicU64, Ordering};
    static CTR: AtomicU64 = AtomicU64::new(0);

    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0);
    let pid = std::process::id() as u64;
    let ctr = CTR.fetch_add(1, Ordering::Relaxed);

    // Splitmix64-style mixing of three independent entropy sources.
    let mut z = now
        .wrapping_add(ctr.wrapping_mul(0x9E3779B97F4A7C15))
        .wrapping_add(pid.wrapping_mul(0xBF58476D1CE4E5B9));
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
    z ^= z >> 31;
    (z as u32) ^ ((z >> 32) as u32)
}

