/// Top-level on-disk record. One per file at `<plans_dir>/<plan_id>.jsonl`.
///
/// Schema-relevant invariants:
///
/// - `nodes` is the single source of truth for nodes. `depends_on` on each
///   node is the single source of truth for edges (v1 collapses the
///   separate `DagEdge` representation).
/// - `closed: Some(...)` is terminal; subsequent `close` calls return
///   [`PlanError::AlreadyClosed`].
/// - Storage does NOT enforce acyclicity. Use
///   [`PlanRecord::validate_dag`] for callers who want strictness.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct PlanRecord {
    /// `plan_<8 base36 chars>`. Generated by [`PlanRecord::new`].
    pub plan_id: String,
    /// Owning principal. The storage layer does not authorize reads; the
    /// caller is expected to use `get_for_principal` / `update` /
    /// `list_for_principal` to enforce scope.
    pub principal_id: PrincipalId,
    /// Schema version that wrote this record. Always
    /// [`PLAN_SCHEMA_VERSION`] for v1 writes.
    pub schema_version: u32,
    /// Immutable plan title set at creation time. The runtime can rename
    /// via a `replace_title` closure passed to `PlanStorage::update` —
    /// the schema does not require immutability, but the runtime does.
    pub title: String,
    /// Plan creation timestamp.
    pub created_at: DateTime<Utc>,
    /// Last mutation timestamp; updated by every `PlanStorage::update` /
    /// `PlanStorage::close`.
    pub updated_at: DateTime<Utc>,
    /// Plan nodes in insertion order. The runtime orders them via
    /// dependency resolution; this vec preserves writer intent.
    pub nodes: Vec<PlanNode>,
    /// Terminal state. `None` while the plan is open.
    pub closed: Option<ClosedState>,
}

impl PlanRecord {
    /// Construct a fresh `PlanRecord` from caller-supplied inputs.
    ///
    /// Generation of `plan_id`, `schema_version`, and timestamps is the
    /// only work the constructor does — the storage layer (`create`)
    /// invokes this and then writes the result atomically.
    pub fn new(principal_id: PrincipalId, title: String, mut nodes: Vec<PlanNode>) -> Self {
        let now = Utc::now();
        // Stamp each newly-supplied node with creation timestamps so the
        // caller doesn't have to.
        for n in &mut nodes {
            n.created_at = now;
            n.updated_at = now;
        }
        Self {
            plan_id: format!("plan_{}", base36_id(rand_u32())),
            principal_id,
            schema_version: PLAN_SCHEMA_VERSION,
            title,
            created_at: now,
            updated_at: now,
            nodes,
            closed: None,
        }
    }

    /// True iff any node is not `Completed` and the plan isn't closed.
    /// This is the predicate the runtime checks before re-injecting a plan
    /// into a fresh session's context.
    pub fn has_unresolved_nodes(&self) -> bool {
        if self.closed.is_some() {
            return false;
        }
        self.nodes
            .iter()
            .any(|n| !matches!(n.status, PlanNodeStatus::Completed { .. }))
    }

    /// All `Pending` nodes whose `depends_on` set is entirely `Completed`.
    /// Used by the runtime to compute the "next actionable" surface.
    pub fn ready_nodes(&self) -> Vec<&PlanNode> {
        let completed: HashSet<&NodeId> = self
            .nodes
            .iter()
            .filter(|n| matches!(n.status, PlanNodeStatus::Completed { .. }))
            .map(|n| &n.node_id)
            .collect();

        self.nodes
            .iter()
            .filter(|n| matches!(n.status, PlanNodeStatus::Pending))
            .filter(|n| n.depends_on.iter().all(|dep| completed.contains(dep)))
            .collect()
    }

    /// All `InProgress` nodes. In v1, the schema permits multiple; the
    /// agent (not the storage layer) is responsible for single-track
    /// discipline. v2 may add a runtime-enforced single-focus invariant.
    pub fn current_focus_nodes(&self) -> Vec<&PlanNode> {
        self.nodes
            .iter()
            .filter(|n| matches!(n.status, PlanNodeStatus::InProgress))
            .collect()
    }

    /// DFS cycle check. Returns `Err(PlanError::InvalidNodeId)` if a
    /// `depends_on` references a node that doesn't exist; returns
    /// `Err(CorruptCycle)` if the graph has a cycle. Storage does NOT
    /// call this — it's available to the runtime for callers who want
    /// strictness on `create`.
    pub fn validate_dag(&self) -> Result<()> {
        let ids: HashSet<&NodeId> = self.nodes.iter().map(|n| &n.node_id).collect();

        // First pass: every depends_on target must exist.
        for n in &self.nodes {
            for dep in &n.depends_on {
                if !ids.contains(dep) {
                    return Err(PlanError::InvalidNodeId(format!(
                        "node {} depends on missing node {}",
                        n.node_id.as_str(),
                        dep.as_str()
                    )));
                }
            }
        }

        // Second pass: cycle check via DFS with white/grey/black coloring.
        // Implemented by *index* into `nodes` — values, not references —
        // because stacked references into a borrowed graph fragment fight
        // the borrow checker on multi-branch DFS. Indices are stable for
        // the duration of a single call.
        #[derive(Debug, Copy, Clone, Eq, PartialEq)]
        enum Color {
            White,
            Grey,
            Black,
        }
        let mut color: Vec<Color> = vec![Color::White; self.nodes.len()];

        // Build a forward adjacency by index: dep -> [things that depend on dep].
        // The dep-existence check above guarantees all `deps[j]` indices
        // are valid.
        let mut forward: Vec<Vec<usize>> = vec![Vec::new(); self.nodes.len()];
        let nodes_by_id: std::collections::HashMap<&NodeId, usize> = self
            .nodes
            .iter()
            .enumerate()
            .map(|(i, n)| (&n.node_id, i))
            .collect();
        for (i, n) in self.nodes.iter().enumerate() {
            for dep in &n.depends_on {
                let j = *nodes_by_id.get(dep).expect("dep existence checked above");
                forward[j].push(i);
            }
        }

        // Iterative DFS: each frame holds the remaining-neighbors list of
        // one frame-node. `frame_nodes[i]` parallels `stack[i]` and is
        // the canonical node id for that frame. Standard 3-color DFS.
        let mut stack: Vec<Vec<usize>> = Vec::new();
        let mut frame_nodes: Vec<usize> = Vec::new();

        for start in 0..self.nodes.len() {
            if color[start] != Color::White {
                continue;
            }
            color[start] = Color::Grey;
            stack.push(forward[start].clone());
            frame_nodes.push(start);

            while !stack.is_empty() {
                // Scoped borrow: `last_mut()` and `pop()` are on a single
                // expression so the mutable borrow ends before the match.
                let next_opt = stack.last_mut().unwrap().pop();
                match next_opt {
                    Some(next) => match color[next] {
                        Color::White => {
                            color[next] = Color::Grey;
                            stack.push(forward[next].clone());
                            frame_nodes.push(next);
                        }
                        Color::Grey => {
                            return Err(PlanError::InvalidNodeId(format!(
                                "plan has cycle through node {}",
                                self.nodes[next].node_id.as_str()
                            )));
                        }
                        Color::Black => {}
                    },
                    None => {
                        // Frame exhausted: mark Black and pop.
                        let done = frame_nodes.pop().unwrap();
                        color[done] = Color::Black;
                        stack.pop();
                    }
                }
            }
        }

        Ok(())
    }
}

