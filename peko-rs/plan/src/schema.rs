/// A single step inside a [`PlanRecord`].
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct PlanNode {
    /// `node_<8 base36 chars>`.
    pub node_id: NodeId,
    /// Human title; max length is not enforced — caller can truncate if
    /// the runtime wants.
    pub step: String,
    /// Current state. Single source of truth for "where this node is".
    pub status: PlanNodeStatus,
    /// Dependencies on other nodes in the same plan. Order-independent.
    /// Empty means "no dependencies (can be `Pending` immediately)".
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub depends_on: Vec<NodeId>,
    /// Per-node output / artifacts / decided_by. `Some` once the node
    /// transitions away from `Pending`/`InProgress`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub evidence: Option<NodeEvidence>,
    /// Redundant fast-access mirror of `status::Blocked { reason }`.
    /// Kept so UI code can render blockers without pattern-matching the
    /// status. Schema-driven code should prefer `status`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub blocked_reason: Option<String>,
    /// Node creation timestamp.
    pub created_at: DateTime<Utc>,
    /// Last mutation timestamp; updated whenever status / evidence /
    /// blocked_reason / depends_on change. Note: not updated for
    /// companion-record (`PlanRecord::updated_at`) mutations — that
    /// field is the *record's* last-touch.
    pub updated_at: DateTime<Utc>,
}

