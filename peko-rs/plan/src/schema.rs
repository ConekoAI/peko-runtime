//! Plan storage schema (v1).
//!
//! The on-disk shape of a [`PlanRecord`]. One record per file at
//! `<plans_dir>/<plan_id>.jsonl`, written via [`crate::PlanStorage`] with
//! `FileLock`-coordinated atomic replacement.
//!
//! This file owns:
//!
//! - The serializable record type ([`PlanRecord`]) and its node ([`PlanNode`])
//!   and status ([`PlanNodeStatus`]) enums.
//! - The [`NodeId`] newtype used to key dependencies and identify nodes
//!   across the record.
//! - Helper queries ([`PlanRecord::has_unresolved_nodes`],
//!   [`PlanRecord::ready_nodes`], [`PlanRecord::current_focus_nodes`],
//!   [`PlanRecord::validate_dag`]) that the runtime can call without
//!   touching storage.
//!
//! It deliberately does NOT own: edge representation (encoded inline as
//! [`PlanNode::depends_on`]), per-node attempt history (use
//! `PlanNodeStatus::Failed` as the single source of truth in v1), or the
//! runtime-derived `current_focus` (computed by
//! [`PlanRecord::current_focus_nodes`]).
//!
//! All enums that may gain variants in future schema versions are marked
//! `#[non_exhaustive]` so v1 readers tolerate v2 writes.

use std::collections::HashSet;
use std::fmt;

use chrono::{DateTime, Utc};
use peko_subject::PrincipalId;
use serde::{Deserialize, Serialize};

use crate::error::{PlanError, Result};

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

/// Schema version of the on-disk record. Bumped when an incompatible change
/// is made; the `schema_version` field on [`PlanRecord`] carries the version
/// that wrote a given record. u32 to leave headroom for the workspace's
/// lifetime.
pub const PLAN_SCHEMA_VERSION: u32 = 1;

/// Length of the random suffix in generated ids (`plan_<suffix>`,
/// `node_<suffix>`). Eight base36 chars gives 36^8 ≈ 2.8T possibilities —
/// comfortable for in-process id generation.
pub const ID_SUFFIX_LEN: usize = 8;

/// Lowercase base36 alphabet `[0-9a-z]`. Matches the convention in
/// `DATA_MODEL.md` §1.4.
const BASE36: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyz";

/// Format a `u32` into exactly [`ID_SUFFIX_LEN`] lowercase base36 chars,
/// most-significant-digit first, with leading zeros.
fn base36_id(n: u32) -> String {
    let mut out = [b'0'; ID_SUFFIX_LEN];
    let mut v = n;
    for slot in out.iter_mut().rev() {
        *slot = BASE36[(v % 36) as usize];
        v /= 36;
    }
    String::from_utf8(out.to_vec()).expect("BASE36 is valid ASCII; cannot fail")
}

fn parse_id_suffix(s: &str, prefix: &str) -> Result<String> {
    let rest = s.strip_prefix(prefix).ok_or_else(|| {
        PlanError::InvalidNodeId(format!("missing {prefix} prefix: {s:?}"))
    })?;
    if rest.len() != ID_SUFFIX_LEN {
        return Err(PlanError::InvalidNodeId(format!(
            "expected {ID_SUFFIX_LEN} base36 chars after {prefix:?}, got {} in {s:?}",
            rest.len()
        )));
    }
    if !rest.bytes().all(|b| BASE36.contains(&b)) {
        return Err(PlanError::InvalidNodeId(format!(
            "non-base36 chars in suffix of {s:?}"
        )));
    }
    Ok(rest.to_string())
}

