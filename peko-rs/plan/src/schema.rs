/// Lifecycle state of a single [`PlanNode`].
///
/// `#[non_exhaustive]` so future schemas can add `Skipped`, `Cancelled`,
/// or refined `Failed` variants without breaking v1 readers.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[non_exhaustive]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum PlanNodeStatus {
    /// Not yet ready to act on (or its dependencies are not satisfied).
    Pending,
    /// Currently being worked on. Single-track is the convention; the
    /// storage layer permits multiple.
    InProgress,
    /// Done. `completed_at` is the wall-clock when the transition
    /// happened (mirrors the last `updated_at`, but carried in the
    /// variant payload for downstream serialization).
    Completed {
        completed_at: DateTime<Utc>,
    },
    /// Blocked on something outside the plan's control. Carries a
    /// human-readable reason and the timestamp of when the blocker was
    /// first recorded (vs. `last_attempt_at` for `Failed`).
    Blocked {
        reason: String,
        since: DateTime<Utc>,
    },
    /// Failed after attempts. Carry last-attempt timestamp and reason.
    /// v2 may add an inline `Vec<AttemptRecord>` if retry lineage becomes
    /// important; for now the runtime records retried failures by bumping
    /// this variant's `last_attempt_at` and appending a sibling evidence
    /// entry.
    Failed {
        reason: String,
        last_attempt_at: DateTime<Utc>,
    },
}

