/// Per-node recorded result. `Some` once the node transitions away from
/// `Pending`/`InProgress`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct NodeEvidence {
    /// Short textual result. Long-form output should go to `artifacts`
    /// (paths) or to a referenced session record.
    pub output: String,
    /// Free-form list of artifact references — file paths, session ids,
    /// commit SHAs, URLs. Not validated by the storage layer.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub artifacts: Vec<String>,
    /// Who produced this evidence. Free-form in v1; v2 may type as
    /// `peko_subject::Subject`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub decided_by: Option<String>,
}

