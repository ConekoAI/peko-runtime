    fn principal_id_display_and_serde_round_trip() {
        let p = PrincipalId::generate();
        let json = serde_json::to_string(&p).expect("ser");
        let back: PrincipalId = serde_json::from_str(&json).expect("de");
        assert_eq!(back, p);
        assert_eq!(back.to_string(), p.to_string());
    }
