/// Terminal state of a [`PlanRecord`]. `#[non_exhaustive]` so v2 can
/// carry a `closed_by` without breaking v1 readers.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[non_exhaustive]
pub struct ClosedState {
    pub closed_at: DateTime<Utc>,
    pub reason: String,
}

impl ClosedState {
    /// Construct a [`ClosedState`] with `closed_at = now()`. The
    /// `#[non_exhaustive]` attribute blocks cross-crate struct
    /// expressions, so external callers (test fixtures, the
    /// `peko_plan` tool surface) need this constructor.
    #[must_use]
    pub fn new(reason: String) -> Self {
        Self {
            closed_at: Utc::now(),
            reason,
        }
    }
}

